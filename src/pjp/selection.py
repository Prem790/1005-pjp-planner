"""Select focus outlets under visit budgets and optimistic travel screening.

No dated schedule or route is generated by this stage.
"""
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

from .data import resolve_roots
from .travel import direct_travel_minutes, haversine_km, normal_day_lower_bound


def _bool_series(values,name):
    converted=values.astype(str).str.lower().map({'true':True,'false':False})
    if converted.isna().any():
        raise ValueError(f'{name} must contain explicit True/False values')
    return converted.astype(bool)


def validate_config(config):
    required_constants={'normal_visits_per_day':6,'club_visits_per_month':2,
                        'nonclub_visits_per_month':1,'club_min_gap_days':10}
    for key,value in required_constants.items():
        if config[key]!=value:
            raise ValueError(f'{key} must match assignment value {value}')
    if not config['protect_all_club_outlets'] or not config['fill_normal_day_visit_budget']:
        raise ValueError('Baseline protects all clubs and fills nominal visit capacity')
    if config['max_optional_outlets_per_root']!=1 or config['allow_optional_outlets_of_protected_roots']:
        raise ValueError('Unsupported shared-owner selection policy')
    if config['missing_location_policy']!='simulator_fallback_with_review_flag':
        raise ValueError('Unsupported missing-location policy')
    model=config['travel_model']
    if any(not np.isfinite(model[k]) or model[k]<=0 for k in ['day_minutes','dealer_call_minutes','road_factor','rain_multiplier']):
        raise ValueError('Travel durations, factor and multipliers must be positive and finite')
    if not 0<=model['demand_generation_minutes']<model['day_minutes']:
        raise ValueError('Demand-generation reserve leaves no working time')
    if model['rain_visits_per_day']!=5:
        raise ValueError('Rain-day screening must use five visits')
    for mapping in ['speed_kmh','unknown_location_travel_minutes']:
        if set(model[mapping])!={'metro','upcountry'} or any(not np.isfinite(x) or x<=0 for x in model[mapping].values()):
            raise ValueError(f'Invalid {mapping}')
    as_of=pd.Timestamp(config['as_of'])
    month=pd.Period(config['planning_month'],freq='M')
    if as_of>=month.start_time:
        raise ValueError('Selection snapshot must precede the planning month')
    return model


def select_focus(ranking,dealers,officers,calendar,config):
    model=validate_config(config)
    ranking=ranking.copy()
    dealers=dealers.copy()
    calendar=calendar.copy()
    required={'dealer_id','so_id','root_dealer_id','rank_within_so','priority_score',
              'raw_weighted_value_loss','recent_90_day_net_value','is_club','has_location',
              'recency_category','as_of','planning_month','reason'}
    if not required<=set(ranking):
        raise ValueError(f'Ranking lacks columns: {sorted(required-set(ranking))}')
    if dealers.dealer_id.isna().any() or dealers.dealer_id.duplicated().any():
        raise ValueError('Dealer IDs must be present and unique')
    if ranking.dealer_id.duplicated().any() or set(ranking.dealer_id)!=set(dealers.dealer_id):
        raise ValueError('Ranking must contain each workbook dealer exactly once')
    if ranking.as_of.isna().any() or not ranking.as_of.eq(config['as_of']).all() or not ranking.planning_month.eq(config['planning_month']).all():
        raise ValueError('Ranking snapshot/planning month differs from selection configuration')
    master=dealers.set_index('dealer_id')
    for column in ['so_id','parent_dealer_id','loyalty_club_member','lat','lon']:
        if column not in master:
            raise ValueError(f'Dealer master lacks {column}')
    if not dealers.loyalty_club_member.isin(['Yes','No']).all():
        raise ValueError('Club membership must be explicit')
    if officers.so_id.isna().any() or officers.so_id.duplicated().any():
        raise ValueError('Officer IDs must be present and unique')
    if dealers.so_id.isna().any() or not set(dealers.so_id)<=set(officers.so_id):
        raise ValueError('Dealer owner is missing or unknown')
    roots=resolve_roots(dealers)
    ranking['is_club']=_bool_series(ranking.is_club,'is_club')
    ranking['has_location']=_bool_series(ranking.has_location,'has_location')
    if not ranking.so_id.eq(ranking.dealer_id.map(master.so_id)).all():
        raise ValueError('Ranking ownership disagrees with current dealer master')
    if not ranking.is_club.eq(ranking.dealer_id.map(master.loyalty_club_member.eq('Yes'))).all():
        raise ValueError('Ranking membership disagrees with current dealer master')
    if not ranking.root_dealer_id.eq(ranking.dealer_id.map(roots)).all():
        raise ValueError('Ranking root-owner mapping differs from the workbook')
    actual_location=master.lat.notna() & master.lon.notna()
    if not ranking.has_location.eq(ranking.dealer_id.map(actual_location)).all():
        raise ValueError('Ranking location flags disagree with the workbook')
    for column in ['priority_score','raw_weighted_value_loss','recent_90_day_net_value']:
        ranking[column]=pd.to_numeric(ranking[column],errors='raise')
        if not np.isfinite(ranking[column]).all():
            raise ValueError(f'Non-finite ranking field: {column}')
    if not ranking.priority_score.between(0,100).all() or (ranking.raw_weighted_value_loss<0).any():
        raise ValueError('Ranking scores or raw loss are out of bounds')
    calendar['date']=pd.to_datetime(calendar.date,errors='raise')
    if calendar.date.isna().any() or calendar.date.duplicated().any():
        raise ValueError('Calendar dates must be present and unique')
    if not calendar.working_day.isin(['Yes','No']).all():
        raise ValueError('Calendar working_day must explicitly be Yes or No')
    month=pd.Period(config['planning_month'],freq='M')
    relevant=calendar.loc[calendar.date.dt.to_period('M')==month]
    expected_dates=set(pd.date_range(month.start_time,month.end_time.normalize()))
    if set(relevant.date)!=expected_dates:
        raise ValueError('Planning calendar must cover every day of the planning month')
    if not relevant.working_day.eq('Yes').eq(relevant.date.dt.dayofweek.ne(6)).all():
        raise ValueError('Calendar must mark Monday-Saturday working and Sundays off')
    workdays=sorted(relevant.loc[relevant.working_day.eq('Yes'),'date'])
    if not workdays:
        raise ValueError('No working days supplied')
    # Rank order remains unchanged; constraints explain every deferral separately.
    result=ranking.sort_values(['so_id','priority_score','raw_weighted_value_loss','recent_90_day_net_value','dealer_id'],
                              ascending=[True,False,False,False,True],kind='stable').reset_index(drop=True)
    result['selected']=False
    result['decision_reason']=''
    result['selected_visit_requirement']=0
    result['protected_club']=result.is_club
    result['direct_travel_min_from_start']=np.nan
    result['straight_line_km_from_start']=np.nan
    result['optimistic_six_visit_day_minutes']=np.nan
    result['optimistic_five_visit_rain_day_minutes']=np.nan
    result['normal_day_screen_pass']=False
    result['rain_day_screen_pass']=False
    result['geography_kind']=''
    result['location_review_required']=~result.has_location
    result['shared_owner_review_required']=result.root_dealer_id.map(pd.Series(roots).value_counts()).gt(1)
    budget_minutes=model['day_minutes']-model['demand_generation_minutes']
    budget_visits=len(workdays)*config['normal_visits_per_day']
    summaries={}
    for _,officer in officers.sort_values('so_id').iterrows():
        so=officer.so_id
        indices=result.index[result.so_id==so].tolist()
        if not indices:
            raise ValueError(f'Officer {so} has no ranked dealer universe')
        kind='upcountry' if 'upcountry' in str(officer.geography).lower() else 'metro'
        start=(float(officer.approx_day_start_lat),float(officer.approx_day_start_lon))
        haversine_km(start,start)  # Validate start coordinates even when all dealers are unlocated.
        for idx in indices:
            row=result.loc[idx]
            location=(float(master.loc[row.dealer_id,'lat']),float(master.loc[row.dealer_id,'lon'])) if row.has_location else None
            direct=direct_travel_minutes(start,location,kind,model)
            six=normal_day_lower_bound(direct,config['normal_visits_per_day'],model)
            rain=normal_day_lower_bound(direct*model['rain_multiplier'],model['rain_visits_per_day'],model)
            result.loc[idx,['direct_travel_min_from_start','optimistic_six_visit_day_minutes',
                            'optimistic_five_visit_rain_day_minutes','normal_day_screen_pass','rain_day_screen_pass','geography_kind']]=[
                                direct,six,rain,six<=budget_minutes+1e-9,rain<=budget_minutes+1e-9,kind]
            if location is not None:
                result.loc[idx,'straight_line_km_from_start']=haversine_km(start,location)
        clubs=[idx for idx in indices if result.loc[idx,'is_club']]
        if clubs and (workdays[-1]-workdays[0]).days<config['club_min_gap_days']:
            raise ValueError(f'{so}: calendar cannot support the minimum club gap')
        if len(clubs)*config['club_visits_per_month']>budget_visits:
            raise ValueError(f'{so}: protected club visits exceed monthly capacity')
        impossible=[result.loc[idx,'dealer_id'] for idx in clubs if not result.loc[idx,'normal_day_screen_pass']]
        if impossible:
            raise ValueError(f'{so}: protected club outlets cannot fit a six-visit normal day even optimistically: {impossible}. Resolve constraints rather than silently dropping clubs.')
        slots=0
        protected_roots=set()
        optional_roots=set()
        for idx in clubs:
            result.loc[idx,['selected','decision_reason','selected_visit_requirement']]=[
                True,'protected_club_coverage',config['club_visits_per_month']]
            slots+=config['club_visits_per_month']
            protected_roots.add(result.loc[idx,'root_dealer_id'])
        for idx in indices:
            if result.loc[idx,'selected']:
                continue
            row=result.loc[idx]
            if not row.normal_day_screen_pass:
                result.loc[idx,'decision_reason']='deferred_normal_day_travel_lower_bound'
            elif row.root_dealer_id in protected_roots or row.root_dealer_id in optional_roots:
                result.loc[idx,'decision_reason']='deferred_shared_owner_already_covered'
            elif slots+config['nonclub_visits_per_month']>budget_visits:
                result.loc[idx,'decision_reason']='deferred_monthly_visit_budget'
            else:
                label='selected_commercial_priority' if row.priority_score>0 else 'selected_capacity_fill_zero_priority_signal'
                result.loc[idx,['selected','decision_reason','selected_visit_requirement']]=[
                    True,label,config['nonclub_visits_per_month']]
                slots+=config['nonclub_visits_per_month']
                optional_roots.add(row.root_dealer_id)
        selected=result.loc[indices].loc[lambda x:x.selected]
        total_signal=result.loc[indices,'raw_weighted_value_loss'].sum()
        retained_signal=selected.raw_weighted_value_loss.sum()
        summaries[so]=dict(universe_dealers=len(indices),working_days=len(workdays),
            normal_day_visit_budget=budget_visits,selected_dealers=len(selected),
            club_dealers=int(selected.is_club.sum()),required_visits=int(slots),unfilled_visit_slots=int(budget_visits-slots),
            selected_without_location=int((~selected.has_location).sum()),
            selected_zero_priority_signal=int(selected.priority_score.eq(0).sum()),
            selected_never_purchased=int(selected.recency_category.eq('never_purchased').sum()),
            selected_club_zero_priority_signal=int((selected.is_club & selected.priority_score.eq(0)).sum()),
            selected_owner_groups=selected.root_dealer_id.nunique(),
            selected_rain_lower_bound_failures=int((~selected.rain_day_screen_pass).sum()),
            deferred_normal_day_travel=int(result.loc[indices,'decision_reason'].eq('deferred_normal_day_travel_lower_bound').sum()),
            retained_weighted_loss_signal_fraction=float(retained_signal/total_signal) if total_signal>0 else None,
            selection_status='screened_pending_route_validation' if slots==budget_visits else 'capacity_shortfall_pending_review')
    result['zero_priority_signal']=result.priority_score.eq(0)
    result['selection_version']=config['version']
    # Explicit hard checks, not just score/report generation.
    selected=result.loc[result.selected]
    if not result.loc[result.is_club,'selected'].all():
        raise RuntimeError('Protected club coverage was lost')
    if not selected.normal_day_screen_pass.all():
        raise RuntimeError('Selected a dealer failing the optimistic travel bound')
    if not selected.selected_visit_requirement.between(1,2).all():
        raise RuntimeError('Invalid selected visit requirement')
    if result.decision_reason.eq('').any():
        raise RuntimeError('Selection did not explain every dealer decision')
    return result,summaries


def run_selection(workbook:Path,ranking_path:Path,config_path:Path,out:Path):
    source_hash=hashlib.sha256(workbook.read_bytes()).hexdigest()
    ranking_metadata_path=ranking_path.parent/'ranking_summary.json'
    metadata=json.loads(ranking_metadata_path.read_text())
    if metadata['source_sha256']!=source_hash:
        raise ValueError('Ranking was generated from a different workbook; rerun ranking first')
    config=json.loads(config_path.read_text())
    if metadata['as_of']!=config['as_of'] or metadata['planning_month']!=config['planning_month']:
        raise ValueError('Ranking metadata and selection snapshot disagree')
    with pd.ExcelFile(workbook) as book:
        dealers=pd.read_excel(book,sheet_name='Dealers')
        officers=pd.read_excel(book,sheet_name='Officers')
        calendar=pd.read_excel(book,sheet_name='Planning_Calendar')
    decisions,summaries=select_focus(pd.read_csv(ranking_path),dealers,officers,calendar,config)
    if hashlib.sha256(workbook.read_bytes()).hexdigest()!=source_hash:
        raise RuntimeError('Source workbook changed during focus selection')
    selected=decisions.loc[decisions.selected].copy()
    deferred=decisions.loc[~decisions.selected].copy()
    out.mkdir(parents=True,exist_ok=True)
    for name,frame in [('focus_dealers',selected),('deferred_dealers',deferred),('selection_decisions',decisions)]:
        frame.to_csv(out/f'{name}.csv',index=False,date_format='%Y-%m-%d')
    for so,frame in selected.groupby('so_id'):
        frame.to_csv(out/f'focus_{so}.csv',index=False,date_format='%Y-%m-%d')
    summary=dict(status='provisional_focus_sets_selected',as_of=config['as_of'],planning_month=config['planning_month'],
        version=config['version'],source_sha256=source_hash,source_unchanged=True,
        ranking_sha256=hashlib.sha256(ranking_path.read_bytes()).hexdigest(),
        config_sha256=hashlib.sha256(config_path.read_bytes()).hexdigest(),
        selected_dealers=len(selected),selected_required_visits=int(selected.selected_visit_requirement.sum()),
        full_route_feasibility_verified=False,dated_schedule_generated=False,
        policy='Fill six normal dealer visits per working day; protect clubs; screen optimistic travel bounds; review zero-score selections.',
        officers=summaries)
    (out/'focus_summary.json').write_text(json.dumps(summary,indent=2,allow_nan=False)+'\n')
    lines=['PJP FOCUS SELECTION SUMMARY',
        'Confidential local output. Provisional selection, not a dated schedule or proof of route feasibility.',
        f"Snapshot {config['as_of']}; planning month {config['planning_month']}",
        'Policy: satisfy six normal visits per working day, rather than force exactly 100 distinct accounts.',
        'All club outlets require two visits. Non-club outlets require one. Clubs remain protected regardless of score.',
        'This fills nominal capacity, not weather-adjusted capacity; no completion/adherence result is claimed.',
        'Zero ranking signal does not establish zero business value; such selections are separately flagged.',
        'Travel test is a lower bound. Passing it does not establish a jointly feasible six-stop day.',
        'Unknown locations remain eligible under simulator travel fallbacks and need verification.',
        'All related mandatory club outlets are retained; optional duplicate-owner outlets are deferred.', '']
    for so,stats in summaries.items():
        lines.append(so)
        lines.extend(f'  {key}: {value}' for key,value in stats.items())
        review=deferred.loc[deferred.so_id.eq(so)&deferred.decision_reason.eq('deferred_normal_day_travel_lower_bound')]
        if len(review):
            lines.append('  Travel-deferral review:')
            lines.append(review[['dealer_id','priority_score','straight_line_km_from_start','optimistic_six_visit_day_minutes']].to_string(index=False))
        lines.append('')
    lines.extend(['NEXT STEP',
        'Assign these requirements to actual working dates, protect club spacing, optimize each route,',
        'and repair or explain any route infeasibility without silently dropping mandatory coverage.'])
    (out/'focus_summary.txt').write_text('\n'.join(lines)+'\n')
    print(json.dumps(summary,indent=2,allow_nan=False))
    return decisions,summary
